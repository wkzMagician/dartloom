String windowsInstaller({
  String appName = 'Dartloom App',
  String appVersion = '0.0.0',
}) {
  final slug = _slug(appName);
  final displayName = _displayName(appName);
  return '; Generated by Dartloom. Customize this file if your installer needs extra files.\n'
      '#define MyAppName "${_escape(displayName)}"\n'
      '#ifndef MyAppVersion\n'
      '#define MyAppVersion "${_escape(appVersion)}"\n'
      '#endif\n'
      '#define MyAppExeName "${slug}.exe"\n'
      '[Setup]\n'
      'AppName={#MyAppName}\n'
      'AppVersion={#MyAppVersion}\n'
      'AppVerName={#MyAppName} {#MyAppVersion}\n'
      'DefaultDirName={autopf}\\{#MyAppName}\n'
      'OutputDir=..\\dist\n'
      'OutputBaseFilename=${slug}-{#MyAppVersion}-windows-x64-setup\n'
      'Compression=lzma2\n'
      'SolidCompression=yes\n'
      'ArchitecturesAllowed=x64compatible\n'
      'ArchitecturesInstallIn64BitMode=x64compatible\n'
      'PrivilegesRequired=lowest\n'
      '[Files]\n'
      'Source: "..\\build\\windows\\x64\\runner\\Release\\*"; DestDir: "{app}"; Flags: ignoreversion recursesubdirs createallsubdirs\n'
      '[Icons]\n'
      'Name: "{autoprograms}\\{#MyAppName}"; Filename: "{app}\\{#MyAppExeName}"\n'
      '[Run]\n'
      'Filename: "{app}\\{#MyAppExeName}"; Description: "Launch {#MyAppName}"; Flags: nowait postinstall skipifsilent\n';
}

String cloudBuildWorkflow({String appName = 'dartloom_app'}) =>
    _cloudBuild(appName);

String _cloudBuild(String appName) => '''name: Dartloom Cloud Build

on:
  workflow_dispatch:
    inputs:
      platform: { required: true, type: string }
      git_ref: { required: true, type: string }
      mode: { required: true, default: release, type: string }

permissions:
  contents: read

jobs:
  matrix:
    runs-on: ubuntu-latest
    outputs:
      platforms: \${{ steps.set-matrix.outputs.platforms }}
    steps:
      - id: set-matrix
        run: |
          if [ "\${{ inputs.platform }}" = "all" ]; then
            echo 'platforms=["windows","linux","macos","android","ios","web"]' >> "\$GITHUB_OUTPUT"
          else
            echo 'platforms=["\${{ inputs.platform }}"]' >> "\$GITHUB_OUTPUT"
          fi

  build:
    needs: matrix
    strategy:
      fail-fast: false
      matrix:
        platform: \${{ fromJSON(needs.matrix.outputs.platforms) }}
    runs-on: \${{ matrix.platform == 'windows' && 'windows-latest' || (matrix.platform == 'macos' || matrix.platform == 'ios') && 'macos-latest' || 'ubuntu-latest' }}
    steps:
      - uses: actions/checkout@v4
        with:
          ref: \${{ inputs.git_ref }}
      - name: Install Linux build dependencies
        if: \${{ matrix.platform == 'linux' }}
        run: |
          sudo apt-get update
          sudo apt-get install -y clang cmake ninja-build pkg-config libgtk-3-dev liblzma-dev zip
      - uses: subosito/flutter-action@v2
        with:
          flutter-version: '3.47.0'
      - run: flutter pub get
      - name: Install Windows packaging tools
        if: \${{ matrix.platform == 'windows' }}
        run: choco install innosetup --no-progress -y
      - name: Build platform
        shell: bash
        run: |
          case "\${{ matrix.platform }}" in
            android) flutter build apk --\${{ inputs.mode }} && flutter build appbundle --\${{ inputs.mode }} ;;
            ios) flutter build ios --\${{ inputs.mode }} --no-codesign ;;
            *) flutter build \${{ matrix.platform }} --\${{ inputs.mode }} ;;
          esac
      - name: Package artifact
        shell: bash
        run: |
          set -euo pipefail
          mkdir -p artifact
          app='${_slug(appName)}'
          mode='\${{ inputs.mode }}'
          case "\${{ matrix.platform }}" in
            android)
              cp "build/app/outputs/flutter-apk/app-\$mode.apk" "artifact/\${app}-android.apk"
              cp "build/app/outputs/bundle/\$mode/app-\$mode.aab" "artifact/\${app}-android.aab"
              ;;
            ios)
              mkdir -p Payload
              cp -R build/ios/iphoneos/Runner.app Payload/
              zip -qr "artifact/\${app}-ios.ipa" Payload
              ;;
            macos)
              app_path=\$(find "build/macos/Build/Products" -maxdepth 2 -name '*.app' -type d | head -n 1)
              ditto -c -k --keepParent "\$app_path" "artifact/\${app}-macos.zip"
              ;;
            windows)
              powershell -NoProfile -Command '\$version = (Select-String -Path pubspec.yaml -Pattern "^version:\\s*([0-9]+\\.[0-9]+\\.[0-9]+)").Matches.Groups[1].Value; if (-not \$version) { throw "pubspec.yaml version not found" }; & (Get-Command ISCC.exe -ErrorAction Stop).Source "/DMyAppVersion=\$version" installer\\windows.iss; Copy-Item -Path "dist\\*.exe" -Destination artifact -Force'
              ;;
            linux)
              tar -czf "artifact/\${app}-linux-x64.tar.gz" -C "build/linux/x64/\$mode" bundle
              ;;
            web)
              (cd build/web && zip -qr "../../artifact/\${app}-web.zip" .)
              ;;
          esac
          printf '{"schema_version":1,"platform":"%s","commit":"%s","files":[]}' "\${{ matrix.platform }}" "\${{ github.sha }}" > artifact/dartloom-build.json
      - uses: actions/upload-artifact@v4
        with:
          name: dartloom-\${{ matrix.platform }}
          path: artifact
''';

