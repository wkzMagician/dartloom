String releaseWorkflow(DartloomConfig config,
    {String appName = 'dartloom_app'}) {
  final jobs =
      config.platforms.map((platform) => _releaseJob(platform, appName));
  final needs = config.platforms.map((platform) => platform.name).join(', ');
  return '''name: Release

on:
  push:
    branches: [main]
    tags: ['v*']
  workflow_dispatch:

permissions:
  contents: write

jobs:
${jobs.join('\n')}
  release:
    needs: [$needs]
    if: \${{ startsWith(github.ref, 'refs/tags/v') && !failure() && !cancelled() }}
    runs-on: ubuntu-latest
    steps:
      - uses: actions/download-artifact@v4
        with:
          path: downloaded_artifacts
      - name: Collect release files
        shell: bash
        run: |
          set -euo pipefail
          mkdir -p release_files
          find downloaded_artifacts -type f ! -name 'dartloom-build.json' -exec cp {} release_files/ \\;
      - uses: softprops/action-gh-release@v2
        with:
          generate_release_notes: true
          overwrite_files: true
          files: release_files/*
''';
}

String _releaseJob(TargetPlatform platform, String appName) {
  final slug = _slug(appName);
  final runner = switch (platform) {
    TargetPlatform.android ||
    TargetPlatform.linux ||
    TargetPlatform.web =>
      'ubuntu-latest',
    TargetPlatform.ios || TargetPlatform.macos => 'macos-latest',
    TargetPlatform.windows => 'windows-latest',
  };
  final linuxDependencies = platform == TargetPlatform.linux
      ? '''      - name: Install Linux build dependencies
        run: |
          sudo apt-get update
          sudo apt-get install -y clang cmake ninja-build pkg-config libgtk-3-dev liblzma-dev zip
'''
      : '';
  final windowsInstall = platform == TargetPlatform.windows
      ? '      - run: choco install innosetup --no-progress -y\n'
      : '';
  final build = switch (platform) {
    TargetPlatform.android =>
      '      - run: flutter build apk --release\n      - run: flutter build appbundle --release',
    TargetPlatform.ios =>
      '      - run: flutter build ios --release --no-codesign',
    TargetPlatform.macos => '      - run: flutter build macos --release',
    TargetPlatform.windows => '      - run: flutter build windows --release',
    TargetPlatform.linux => '      - run: flutter build linux --release',
    TargetPlatform.web => '      - run: flutter build web --release',
  };
  final package = switch (platform) {
    TargetPlatform.android => '''      - name: Package Android
        shell: bash
        run: |
          mkdir -p dist
          cp build/app/outputs/flutter-apk/app-release.apk dist/${slug}-android.apk
          cp build/app/outputs/bundle/release/app-release.aab dist/${slug}-android.aab
''',
    TargetPlatform.ios => '''      - name: Package iOS IPA
        shell: bash
        run: |
          mkdir -p dist Payload
          cp -R build/ios/iphoneos/Runner.app Payload/
          zip -qr dist/${slug}-ios.ipa Payload
''',
    TargetPlatform.macos => '''      - name: Package macOS app
        shell: bash
        run: |
          mkdir -p dist
          app_path=\$(find build/macos/Build/Products/Release -maxdepth 1 -name '*.app' -type d | head -n 1)
          ditto -c -k --keepParent "\$app_path" dist/${slug}-macos.zip
''',
    TargetPlatform.windows => '''      - name: Package Windows installer
        shell: pwsh
        run: |
          New-Item -ItemType Directory -Force -Path dist
          \$version = (Select-String -Path pubspec.yaml -Pattern '^version:\\s*([0-9]+\\.[0-9]+\\.[0-9]+)').Matches.Groups[1].Value
          if (-not \$version) { throw "pubspec.yaml version not found" }
          & (Get-Command ISCC.exe -ErrorAction Stop).Source "/DMyAppVersion=\$version" installer\\windows.iss
''',
    TargetPlatform.linux => '''      - name: Package Linux bundle
        shell: bash
        run: |
          mkdir -p dist
          tar -czf dist/${slug}-linux-x64.tar.gz -C build/linux/x64/release bundle
''',
    TargetPlatform.web => '''      - name: Package Web
        shell: bash
        run: |
          mkdir -p dist
          (cd build/web && zip -qr ../../dist/${slug}-web.zip .)
''',
  };
  final artifact = platform == TargetPlatform.windows ? 'dist/*.exe' : 'dist/*';
  return '''  ${platform.name}:
    runs-on: $runner
    steps:
      - uses: actions/checkout@v4
${linuxDependencies}      - uses: subosito/flutter-action@v2
        with:
          flutter-version: '3.47.0'
      - run: flutter pub get
${windowsInstall}$build
$package      - uses: actions/upload-artifact@v4
        with:
          name: ${platform.name}
          path: $artifact
''';
}

String _slug(String value) {
  final slug = value
      .trim()
      .replaceAll(RegExp(r'[^A-Za-z0-9_-]+'), '_')
      .replaceAll(RegExp(r'_+'), '_');
  return slug.isEmpty ? 'dartloom_app' : slug.toLowerCase();
}

String _displayName(String value) => value
    .replaceAll(RegExp(r'[_-]+'), ' ')
    .split(' ')
    .where((part) => part.isNotEmpty)
    .map((part) => '${part[0].toUpperCase()}${part.substring(1)}')
    .join(' ');

String _escape(String value) => value.replaceAll('"', '""');
